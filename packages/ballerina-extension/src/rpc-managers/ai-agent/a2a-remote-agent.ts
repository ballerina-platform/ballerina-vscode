import { A2aAgentCardInfo, A2aCardFetchResponse, A2aSecuritySchemeInfo, A2aSkillInfo } from "@wso2/ballerina-core";

/**
 * Pure helpers behind "Use Remote Agent (A2A)": read an Agent Card and name the toolkit variable. The code that
 * connects an agent to the remote agent is generated by the language server (`A2A_TOOL_KIT` node).
 */

const WELL_KNOWN = "/.well-known/agent-card.json";
const FETCH_TIMEOUT_MS = 8000;
const HTTP_JSON = "HTTP+JSON";

/** The agent's base URL: the source without a query, fragment, trailing slash or `/.well-known/...` suffix. */
export function toBaseUrl(source: string): string {
    let url = source.trim().replace(/[?#].*$/, "");
    const idx = url.indexOf("/.well-known/");
    if (idx >= 0) {
        url = url.substring(0, idx);
    }
    return url.replace(/\/+$/, "");
}

export function cardUrlOf(source: string): string {
    return toBaseUrl(source) + WELL_KNOWN;
}

function asStrings(value: unknown): string[] {
    return Array.isArray(value) ? value.filter((v): v is string => typeof v === "string") : [];
}

function schemeKind(name: string, scheme: any): string {
    if (!scheme || typeof scheme !== "object") {
        return name;
    }
    const key = String(scheme.type ?? Object.keys(scheme)[0] ?? "").toLowerCase();
    const body = scheme.type ? scheme : (Object.values(scheme)[0] as any) ?? {};
    if (key.includes("http")) {
        const s = String(body.scheme ?? "").toLowerCase();
        return s === "bearer" ? "Bearer" : s === "basic" ? "Basic" : s ? `HTTP ${body.scheme}` : "HTTP";
    }
    if (key.includes("apikey")) { return "API key"; }
    if (key.includes("oauth2")) { return "OAuth2"; }
    if (key.includes("openid")) { return "OpenID Connect"; }
    if (key.includes("mutualtls")) { return "Mutual TLS"; }
    return name;
}

/** Reads the fields the form shows from an Agent Card, v1.0 or earlier. */
export function toCardInfo(json: any): A2aAgentCardInfo {
    const interfaces: any[] = Array.isArray(json?.supportedInterfaces) ? json.supportedInterfaces : [];
    const preferred = interfaces.find((i) => isHttpJson(i?.protocolBinding)) ?? interfaces[0];
    const caps = json?.capabilities ?? {};
    const schemes = json?.securitySchemes && typeof json.securitySchemes === "object" ? json.securitySchemes : {};
    const securitySchemes: A2aSecuritySchemeInfo[] = Object.entries(schemes)
        .map(([name, scheme]) => ({ name, kind: schemeKind(name, scheme) }));
    const skills: A2aSkillInfo[] = (Array.isArray(json?.skills) ? json.skills : []).map((s: any) => ({
        id: String(s?.id ?? ""),
        name: String(s?.name ?? s?.id ?? ""),
        description: String(s?.description ?? ""),
        tags: asStrings(s?.tags),
        examples: asStrings(s?.examples),
    }));
    return {
        name: String(json?.name ?? ""),
        description: String(json?.description ?? ""),
        version: String(json?.version ?? ""),
        provider: json?.provider?.organization ? String(json.provider.organization) : undefined,
        documentationUrl: json?.documentationUrl ? String(json.documentationUrl) : undefined,
        endpointUrl: preferred?.url ?? json?.url,
        protocolBinding: preferred?.protocolBinding,
        protocolVersion: preferred?.protocolVersion ?? json?.protocolVersion,
        protocolBindings: interfaces.map((i) => String(i?.protocolBinding ?? "")).filter(Boolean),
        streaming: caps.streaming === true,
        pushNotifications: caps.pushNotifications === true,
        extendedAgentCard: caps.extendedAgentCard === true,
        securitySchemes,
        inputModes: asStrings(json?.defaultInputModes),
        outputModes: asStrings(json?.defaultOutputModes),
        skills,
    };
}

function isHttpJson(binding: unknown): boolean {
    return String(binding ?? "").toUpperCase().replace(/\s+/g, "").includes(HTTP_JSON);
}

/**
 * Why `ai:A2aToolKit` cannot call the agent, or undefined when it can. The toolkit speaks the HTTP+JSON binding, so
 * a card that lists interfaces but none of them HTTP+JSON is an agent it cannot reach.
 */
export function unsupportedReason(card: A2aAgentCardInfo): string | undefined {
    if (card.protocolBindings.length === 0 || card.protocolBindings.some(isHttpJson)) {
        return undefined;
    }
    return `This agent only offers ${card.protocolBindings.join(", ")}. The A2A toolkit calls agents over HTTP+JSON.`;
}

/**
 * `Trip Planner Agent` becomes `tripPlannerAgent`, and `Weather` becomes `weatherAgent`: the variable always ends in
 * `Agent`. Anything that isn't a valid identifier start gets a prefix.
 */
export function toolkitVariableName(cardName: string): string {
    const words = cardName.split(/[^A-Za-z0-9]+/).filter(Boolean);
    if (words.length > 1 && words[words.length - 1].toLowerCase() === "agent") {
        words.pop();
    } else if (words.length === 1 && words[0].toLowerCase() === "agent") {
        words.pop();
    }
    if (words.length === 0) {
        return "remoteAgent";
    }
    words.push("Agent");
    const camel = words
        .map((w, i) => (i === 0 ? w.charAt(0).toLowerCase() + w.slice(1) : w.charAt(0).toUpperCase() + w.slice(1)))
        .join("");
    return /^[A-Za-z_]/.test(camel) ? camel : `agent${camel.charAt(0).toUpperCase()}${camel.slice(1)}`;
}

/**
 * Fetches an Agent Card from a URL, or reads one pasted as JSON. `headers` are sent with the request, for an agent
 * behind a gateway that asks for a credential on the card too.
 */
export async function fetchAgentCard(source: string, headers: Record<string, string> = {},
    fetchImpl: typeof fetch = fetch): Promise<A2aCardFetchResponse> {
    const text = source.trim();
    if (!text) {
        return { error: "Enter the agent's URL or paste its Agent Card." };
    }
    let json: any;
    let agentUrl: string | undefined;
    if (text.startsWith("{")) {
        try {
            json = JSON.parse(text);
        } catch {
            return { error: "That isn't valid JSON." };
        }
    } else {
        if (!/^https?:\/\//i.test(text)) {
            return { error: "The URL must start with http:// or https://." };
        }
        agentUrl = toBaseUrl(text);
        const controller = new AbortController();
        const timer = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS);
        try {
            const res = await fetchImpl(cardUrlOf(text), {
                signal: controller.signal,
                headers: { Accept: "application/json", ...headers },
            });
            if (res.status === 401 || res.status === 403) {
                return {
                    error: `The agent asked for credentials (${res.status}). Choose how to authenticate below, then fetch the card again.`,
                };
            }
            if (!res.ok) {
                return { error: `The agent answered ${res.status} for ${WELL_KNOWN}. Check the URL.` };
            }
            json = await res.json();
        } catch (e) {
            const reason = (e as Error)?.name === "AbortError" ? "timed out" : "couldn't be reached";
            return { error: `${agentUrl} ${reason}. Is the agent running?` };
        } finally {
            clearTimeout(timer);
        }
    }
    const card = toCardInfo(json);
    if (!card.name) {
        return { error: "That doesn't look like an Agent Card: it has no name." };
    }
    return {
        card,
        agentUrl,
        fromJson: agentUrl === undefined,
        toolkitName: toolkitVariableName(card.name),
        unsupported: unsupportedReason(card),
    };
}
